// Writes js/assets.js from the disassembly in orig-src/assembly:
//   ds, cs    the program's data and code segments, rebuilt byte for byte (tools/image.js)
//   sym       data-segment label -> offset
//   sprites   every bitmap the engine draws from unchanging data, found by playing the game
//             headlessly through the title and every room: [offset, cx (rows<<8 | words),
//             blit kind, screens bitmask, nearest label]. Screens: bit 0 title/menus,
//             bit 1+n level n (0 = the alley).
// Run: node tools/extract.js   (deterministic: seeded input and Math.random)
'use strict';
const fs = require('fs');
const path = require('path');
const build = require('./image');
const OUT = path.join(__dirname, '..', 'js', 'assets.js');

const img = build();
const sym = {};
for (const k of Object.keys(img.dsLabels).sort()) sym[k] = img.dsLabels[k];

const b64 = (u8) => Buffer.from(u8).toString('base64');
const wrap = (s) => s.replace(/.{1,120}/g, (m) => `'${m}'+\n`).replace(/\+\n$/, '');
function write(sprites) {
  fs.writeFileSync(OUT, `// Generated by tools/extract.js from orig-src/assembly. Do not edit.
'use strict';
const ASSETS = (() => {
  const dec = (s) => { const b = atob(s), u = new Uint8Array(b.length); for (let i = 0; i < b.length; i++) u[i] = b.charCodeAt(i); return u; };
  return {
    sym: ${JSON.stringify(sym)},
    sprites: [
${sprites.map((s) => '      ' + JSON.stringify(s)).join(',\n')}
    ],
    ds: dec(
${wrap(b64(img.ds))}),
    cs: dec(
${wrap(b64(img.cs))}),
  };
})();
`);
}

// ---- sprite catalogue ---------------------------------------------------------------------------
async function catalogue() {
  const { makeRunner, forceRoom } = require('./headless');
  const found = new Map();                       // "si:cx:kind" -> {si, cx, kind, screens, static}
  const labels = Object.entries(sym).sort((a, b) => a[1] - b[1]);
  const labelOf = (a) => {
    let best = null;
    for (const [k, v] of labels) { if (v <= a) best = [k, v]; else break; }
    return best ? (best[1] === a ? best[0] : `${best[0]}+${(a - best[1]).toString(16)}`) : a.toString(16);
  };
  const size = (cx) => ((cx >> 8) || 256) * (cx & 0xff) * 2;

  async function session(seed, rooms, seconds) {
    process.env.SEED = String(seed);
    let inGame = false, M, $, CGA;
    const r = makeRunner(null, (ctx) => { CGA = ctx.CGA; M = ctx.Game.mem; $ = ctx.Game.sym; hook(); });
    const { Game } = r;
    function hook() { for (const k of ['blit_to_cga', 'blit_transparent', 'blit_masked']) record(k); }
    function record(kind) {
      const f = CGA[kind];
      CGA[kind] = function (src, si, dst, di, cx, ...rest) {
        if (src === M && si < img.ds.length) {
          const n = size(cx);
          let same = si + n <= img.ds.length, any = false;
          for (let i = 0; same && i < n; i++) { if (M[si + i] !== img.ds[si + i]) same = false; if (M[si + i]) any = true; }
          const key = `${si}:${cx}:${kind}`;
          let e = found.get(key);
          if (!e) found.set(key, e = { si, cx, kind, screens: 0, static: true, any: false });
          if (!same) e.static = false;
          if (any) e.any = true;
          e.screens |= inGame ? 2 << M[$.level_number] : 1;
        }
        return f.call(this, src, si, dst, di, cx, ...rest);
      };
    }
    let s = seed >>> 0 || 1;
    const rnd = () => { s ^= s << 13; s >>>= 0; s ^= s >> 17; s ^= s << 5; s >>>= 0; return s / 4294967296; };
    const start = [[2, 0x1c], [4, 0x31], [6, 0x25], [8, 0x39]];
    for (const [t, k] of start) { await r.runUntil(t); Game.keyEvent(k, true); await r.runUntil(t + 0.1); Game.keyEvent(k, false); }
    await r.runUntil(10);
    const keys = [0x48, 0x50, 0x4b, 0x4d, 0x48, 0x4b, 0x4d, 0x38, 0x38, 0x39, 0x47, 0x49];
    const held = new Set();
    let t = 10, next = 0, lastForce = 0;
    while (t < seconds) {
      await r.runUntil(t);
      inGame = true;
      if (M[$.lives_count] < 3) M[$.lives_count] = 9;
      if (rooms.length && M[$.level_number] === 0 && t - lastForce > 4) { forceRoom(Game, rooms[next++ % rooms.length]); lastForce = t; }
      if (held.size && rnd() < 0.5) { const k = [...held][Math.floor(rnd() * held.size)]; Game.keyEvent(k, false); held.delete(k); }
      else { const k = keys[Math.floor(rnd() * keys.length)]; if (!held.has(k)) { Game.keyEvent(k, true); held.add(k); } }
      t += 0.05 + rnd() * 0.4;
    }
    Game.stop();
  }
  await session(1, [], 240);
  for (let seed = 2; seed < 6; seed++) await session(seed, [1, 2, 3, 4, 5, 6, 7], 400);
  // Sprites clipped at a screen edge are drawn with fewer rows, or from a later row: fold every
  // row-aligned slice into the largest bitmap of the same width that contains it.
  const all = [...found.values()].filter((e) => e.static && e.any);
  all.sort((a, b) => size(b.cx) - size(a.cx));
  const kept = [];
  for (const e of all) {
    const w = (e.cx & 0xff) * 2;
    const host = kept.find((k) => (k.cx & 0xff) * 2 === w && k.kind === e.kind && k.si <= e.si &&
      e.si + size(e.cx) <= k.si + size(k.cx) && (e.si - k.si) % w === 0);
    if (host) host.screens |= e.screens; else kept.push(e);
  }
  return kept
    .sort((a, b) => a.si - b.si)
    .map((e) => [e.si, e.cx, e.kind.replace('blit_', '').replace('to_cga', 'copy'), e.screens, labelOf(e.si)]);
}

write([]);
catalogue().then((sprites) => {
  write(sprites);
  console.log(`js/assets.js: ds ${img.ds.length}, cs ${img.cs.length}, ${Object.keys(sym).length} symbols, ${sprites.length} sprites`);
  process.exit(0);
}, (e) => { console.error(e); process.exit(1); });
